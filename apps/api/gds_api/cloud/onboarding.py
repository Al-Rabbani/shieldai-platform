"""Client cloud onboarding: the grant artefacts, and nothing secret.

Design decision (19 Nov 2026). GDS never stores a client cloud credential. The client creates a
read-only role that trusts GDS's own principal, gated by a per-tenant ExternalId, and GDS assumes it
for short-lived credentials. The ExternalId is what stops one tenant from pointing a profile at
another tenant's role (the confused-deputy problem), so it is generated here and never chosen by a
caller.

This module builds the grant the client runs. It deliberately contains no secret handling: the only
value it stores is a public identifier (role ARN, subscription, project) plus the ExternalId.
"""
from __future__ import annotations

import json
import os
import secrets
from typing import Any

# The principal clients trust. Overridable so a staging deployment can trust a different account,
# but the default is GDS's own account so a misconfiguration cannot silently trust a stranger.
DEFAULT_TRUST_PRINCIPAL = "arn:aws:iam::696616821372:root"

# Read-only by design. SecurityAudit covers IAM/CloudTrail/Config posture; ReadOnlyAccess covers
# inventory. Neither permits a write, which is the point: the bot proposes, humans approve.
READ_ONLY_POLICIES = (
    "arn:aws:iam::aws:policy/SecurityAudit",
    "arn:aws:iam::aws:policy/ReadOnlyAccess",
)

EXTERNAL_ID_PREFIX = "gds-"


def trust_principal() -> str:
    return os.environ.get("GDS_AWS_TRUST_PRINCIPAL", DEFAULT_TRUST_PRINCIPAL).strip()


def new_external_id() -> str:
    """A fresh, unguessable ExternalId. 128 bits of randomness, prefixed for recognisability."""
    return EXTERNAL_ID_PREFIX + secrets.token_hex(16)


def is_valid_external_id(value: str | None) -> bool:
    if not value or not isinstance(value, str):
        return False
    if not value.startswith(EXTERNAL_ID_PREFIX):
        return False
    suffix = value[len(EXTERNAL_ID_PREFIX):]
    if len(suffix) != 32:
        return False
    # token_hex output is hex; accepting arbitrary text would let a caller pick a guessable value.
    return all(ch in "0123456789abcdef" for ch in suffix)


def aws_cloudformation_template(
    *, external_id: str, role_name: str = "GDS-SecurityReadOnly"
) -> dict[str, Any]:
    """The exact stack a client runs in their own account. Nothing here is a secret."""
    if not is_valid_external_id(external_id):
        raise ValueError("an ExternalId generated by GDS is required")
    return {
        "AWSTemplateFormatVersion": "2010-09-09",
        "Description": (
            "Grants GDS Security OS read-only cross-account access. It creates one IAM role "
            "trusting GDS's principal, gated by an ExternalId unique to this tenant. No secret is "
            "shared. Delete this stack to revoke access immediately."
        ),
        "Resources": {
            "GDSReadOnlyRole": {
                "Type": "AWS::IAM::Role",
                "Properties": {
                    "RoleName": role_name,
                    "Description": "GDS Security OS read-only role. Revoke by deleting this stack.",
                    "MaxSessionDuration": 3600,
                    "AssumeRolePolicyDocument": {
                        "Version": "2012-10-17",
                        "Statement": [
                            {
                                "Effect": "Allow",
                                "Principal": {"AWS": trust_principal()},
                                "Action": "sts:AssumeRole",
                                "Condition": {
                                    "StringEquals": {"sts:ExternalId": external_id}
                                },
                            }
                        ],
                    },
                    "ManagedPolicyArns": list(READ_ONLY_POLICIES),
                },
            }
        },
        "Outputs": {
            "RoleArn": {
                "Description": "Paste this ARN into GDS as the connection's role reference.",
                "Value": {"Fn::GetAtt": ["GDSReadOnlyRole", "Arn"]},
            }
        },
    }


AZURE_STEPS = (
    "1. Create or reuse a GDS service principal (multi-tenant app registration) and note its "
    "application (client) id and object id.",
    "2. Grant that principal the Reader role at subscription or management-group scope. Reader is "
    "read-only; do not grant Contributor.",
    "3. For many subscriptions, delegate through Azure Lighthouse instead of repeating step 2 per "
    "subscription, so one delegation covers the whole estate.",
    "4. Record the subscription id as the connection's native id and the principal id as its role "
    "reference. Authenticate with a certificate or federated credential, not a shared secret.",
)

GCP_STEPS = (
    "1. In the client project, grant the GDS principal roles/viewer and "
    "roles/iam.securityReviewer at project or folder scope.",
    "2. Prefer workload identity federation with an attribute condition over a downloaded service "
    "account key; a key file is a long-lived secret and defeats the point.",
    "3. Record the project id as the connection's native id and the principal as its role reference.",
)


DEFAULT_PLATFORM_USER = "gds-security-scanner"


def with_platform_assume_grant(
    template: dict[str, Any], *, platform_user_name: str = DEFAULT_PLATFORM_USER
) -> dict[str, Any]:
    """Add the identity-side half of the grant, which the role alone does not provide.

    Measured 19 Nov 2026: the platform identity arn:aws:iam::696616821372:user/gds-security-scanner has
    only SecurityAudit attached, and that policy grants sts:GetAccessKeyInfo but NOT sts:AssumeRole.
    So creating the read-only role is only half the grant; without this policy the platform cannot
    assume it. The parameter exists because a client running this stack in a different account has no
    such user, and must set it false rather than have the stack fail on a missing user.
    """
    out = json.loads(json.dumps(template))  # never mutate the caller's dict
    out.setdefault("Parameters", {})["GrantAssumeRoleToPlatformUser"] = {
        "Type": "String",
        "Default": "true",
        "AllowedValues": ["true", "false"],
        "Description": (
            "Set false when this stack runs in a different AWS account from GDS: the platform user "
            "does not exist there, so the role is trusted by principal instead."
        ),
    }
    out["Conditions"] = {
        "IsPlatformAccount": {
            "Fn::Equals": [{"Ref": "GrantAssumeRoleToPlatformUser"}, "true"]
        }
    }
    out["Resources"]["GDSAssumeRoleGrant"] = {
        "Type": "AWS::IAM::Policy",
        "Condition": "IsPlatformAccount",
        "Properties": {
            "PolicyName": "GDS-AssumeReadOnlyRole",
            "Users": [platform_user_name],
            "PolicyDocument": {
                "Version": "2012-10-17",
                "Statement": [
                    {
                        "Effect": "Allow",
                        "Action": "sts:AssumeRole",
                        "Resource": {"Fn::GetAtt": ["GDSReadOnlyRole", "Arn"]},
                    }
                ],
            },
        },
    }
    return out


def onboarding_package(*, provider: str, external_id: str | None) -> dict[str, Any]:
    """Everything a client needs to grant access, plus what GDS will do with it.

    A provider with no automated artefact yet returns documented steps rather than a pretend
    template, so nobody is told a one-click flow exists when it does not.
    """
    provider = (provider or "").strip().lower()
    if provider == "aws":
        if not is_valid_external_id(external_id):
            raise ValueError("an ExternalId generated by GDS is required")
        return {
            "provider": "aws",
            "mechanism": "assume_role_with_external_id",
            "automated": True,
            "external_id": external_id,
            "trust_principal": trust_principal(),
            "read_only_policies": list(READ_ONLY_POLICIES),
            "cloudformation": with_platform_assume_grant(
                aws_cloudformation_template(external_id=external_id)
            ),
            "identity_side_grant": (
                "the stack also grants the platform user sts:AssumeRole on this role, because "
                "SecurityAudit alone does not permit assuming it; set "
                "GrantAssumeRoleToPlatformUser=false for a different account"
            ),
            "what_gds_stores": (
                "the role ARN and this ExternalId only; GDS never receives or stores an access key"
            ),
            "revoke": "delete the CloudFormation stack; access ends immediately",
        }
    if provider == "azure":
        return {
            "provider": "azure",
            "mechanism": "service_principal_reader",
            "automated": False,
            "external_id": external_id,
            "steps": list(AZURE_STEPS),
            "what_gds_stores": "subscription id and principal reference only",
            "revoke": "remove the Reader role assignment, or delete the Lighthouse delegation",
        }
    if provider == "gcp":
        return {
            "provider": "gcp",
            "mechanism": "workload_identity_federation",
            "automated": False,
            "external_id": external_id,
            "steps": list(GCP_STEPS),
            "what_gds_stores": "project id and principal reference only",
            "revoke": "remove the IAM bindings in the client project",
        }
    raise ValueError(f"'{provider}' is not a registered cloud provider")
