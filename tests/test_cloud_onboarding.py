"""Guards for client cloud onboarding.

The rule these protect: GDS must never ask a client for a cloud secret, and the ExternalId that binds
a client's role to this tenant must be generated by GDS rather than chosen by a caller.
"""
import pytest

from gds_api.cloud.onboarding import (
    EXTERNAL_ID_PREFIX,
    READ_ONLY_POLICIES,
    aws_cloudformation_template,
    is_valid_external_id,
    new_external_id,
    onboarding_package,
    trust_principal,
)


def test_external_id_is_generated_by_gds_and_unguessable():
    first, second = new_external_id(), new_external_id()
    assert first.startswith(EXTERNAL_ID_PREFIX)
    assert is_valid_external_id(first)
    assert first != second
    assert len(first) == len(EXTERNAL_ID_PREFIX) + 32


def test_external_id_validation_rejects_caller_chosen_values():
    for bad in (None, "", "abc", "gds-", "gds-" + "z" * 32, "gds-" + "a" * 31):
        assert not is_valid_external_id(bad), bad


def test_aws_template_trusts_gds_with_an_external_id_condition():
    external_id = new_external_id()
    template = aws_cloudformation_template(external_id=external_id)
    role = template["Resources"]["GDSReadOnlyRole"]["Properties"]
    statement = role["AssumeRolePolicyDocument"]["Statement"][0]
    assert statement["Principal"]["AWS"] == trust_principal()
    assert statement["Action"] == "sts:AssumeRole"
    assert statement["Condition"]["StringEquals"]["sts:ExternalId"] == external_id
    assert role["ManagedPolicyArns"] == list(READ_ONLY_POLICIES)
    assert template["Outputs"]["RoleArn"]["Value"] == {"Fn::GetAtt": ["GDSReadOnlyRole", "Arn"]}


def test_aws_template_is_read_only_and_carries_no_secret_material():
    template = aws_cloudformation_template(external_id=new_external_id())
    rendered = str(template).lower()
    for forbidden in ("accesskey", "secretaccesskey", "password", "sessiontoken"):
        assert forbidden not in rendered
    assert all("ReadOnly" in policy or "SecurityAudit" in policy
               for policy in template["Resources"]["GDSReadOnlyRole"]["Properties"]["ManagedPolicyArns"])


def test_aws_template_refuses_a_caller_supplied_external_id():
    with pytest.raises(ValueError):
        aws_cloudformation_template(external_id="not-generated-by-gds")


def test_azure_and_gcp_are_documented_steps_not_a_pretend_one_click():
    for provider in ("azure", "gcp"):
        package = onboarding_package(provider=provider, external_id=new_external_id())
        assert package["automated"] is False
        assert package["steps"], provider
        assert "secret" in package["what_gds_stores"] or "reference" in package["what_gds_stores"]


def test_unknown_provider_is_rejected():
    with pytest.raises(ValueError):
        onboarding_package(provider="oracle", external_id=new_external_id())


def test_template_also_grants_the_platform_user_assume_role():
    """The role alone is not enough: SecurityAudit grants sts:GetAccessKeyInfo, not sts:AssumeRole."""
    from gds_api.cloud.onboarding import onboarding_package

    cfn = onboarding_package(provider="aws", external_id="gds-" + "a1" * 16)["cloudformation"]
    grant = cfn["Resources"]["GDSAssumeRoleGrant"]["Properties"]
    assert grant["PolicyDocument"]["Statement"][0]["Action"] == "sts:AssumeRole"
    assert grant["Users"] == ["gds-security-scanner"]
    assert grant["PolicyDocument"]["Statement"][0]["Resource"] == {
        "Fn::GetAtt": ["GDSReadOnlyRole", "Arn"]
    }
    assert cfn["Parameters"]["GrantAssumeRoleToPlatformUser"]["Default"] == "true"
    assert cfn["Conditions"]["IsPlatformAccount"] == {
        "Fn::Equals": [{"Ref": "GrantAssumeRoleToPlatformUser"}, "true"]
    }


def test_base_template_is_not_mutated_by_the_grant():
    from gds_api.cloud.onboarding import aws_cloudformation_template

    base = aws_cloudformation_template(external_id="gds-" + "a1" * 16)
    assert "GDSAssumeRoleGrant" not in base["Resources"]
    assert "Parameters" not in base
